package com.dbagent.store;

import org.springframework.dao.DataAccessResourceFailureException;
import org.springframework.dao.DuplicateKeyException;
import org.springframework.jdbc.CannotGetJdbcConnectionException;
import org.springframework.jdbc.core.JdbcTemplate;

import java.sql.Types;
import java.util.ArrayList;
import java.util.List;

/**
 * Oracle 19c 방언(운영 대상: 19.8 EE non-CDB, AL32UTF8, MAX_STRING_SIZE=STANDARD - 설계서 1.5절).
 *
 * <p>1단계(2026-10-13)에서는 앱이 이 방언으로 DDL을 실행하지 않는다 - 정의와 렌더링만 있다. 문자열 길이 처리(1333자 초과는 CLOB)는
 * 설계서 2.5절 제안대로이며 오케스트레이터 확인 대기(체크리스트 0-9)다.</p>
 */
public final class OracleStoreDialect extends StoreDialect {

    public static final OracleStoreDialect INSTANCE = new OracleStoreDialect();

    /** VARCHAR2 4000바이트 상한에서 한글(3바이트)만 들어와도 안전한 글자 수(로컬 19.3 실측: 1333자 통과, 1334자 ORA-12899). */
    static final int VARCHAR2_SAFE_CHARS = 1333;
    /** oracle.jdbc.OracleTypes.BINARY_DOUBLE - 이 타입으로 바인드해야 NaN·Infinity를 쓸 수 있다. */
    static final int BINARY_DOUBLE = 101;

    private OracleStoreDialect() {
    }

    @Override
    public StoreType type() {
        return StoreType.ORACLE;
    }

    static boolean isClob(ColumnDef c) {
        return c.type() == ColType.TEXT_LARGE || (c.type() == ColType.VARCHAR && c.length() > VARCHAR2_SAFE_CHARS);
    }

    @Override
    public String renderType(ColumnDef c) {
        switch (c.type()) {
            case VARCHAR:
            case TEXT_LARGE:
                return isClob(c) ? "CLOB" : "VARCHAR2(" + c.length() + " CHAR)";
            case BIGINT:
                return "NUMBER(19)";
            case INTEGER:
                return "NUMBER(10)";
            case BOOL01:
                return "NUMBER(1)";
            case DOUBLE:
                return "BINARY_DOUBLE";
            case IDENTITY:
                // ALWAYS가 아니라 BY DEFAULT ON NULL - 이전 도구가 H2의 원래 id를 그대로 넣을 수 있어야 한다
                return "NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY";
            default:
                throw new IllegalStateException("타입을 알 수 없습니다: " + c.type());
        }
    }

    private String renderColumn(ColumnDef c) {
        StringBuilder sb = new StringBuilder(c.name()).append(' ').append(renderType(c));
        // Oracle은 ""를 NULL로 저장한다 - ""가 들어가는 컬럼은 NOT NULL·DEFAULT ''를 빼야 ORA-01400이 나지 않는다
        boolean emptyDefault = "''".equals(c.defaultSql());
        if (c.defaultSql() != null && !emptyDefault) sb.append(" DEFAULT ").append(c.defaultSql());
        if (c.isNotNull() && !c.isEmptyAsNull() && !emptyDefault) sb.append(" NOT NULL");
        if (c.checkSql() != null) sb.append(" CHECK (").append(c.checkSql()).append(")");
        return sb.toString();
    }

    @Override
    public String renderCreateTable(TableDef t) {
        List<String> parts = new ArrayList<String>();
        for (ColumnDef c : t.columns()) {
            if (wantColumn(c)) parts.add(renderColumn(c));
        }
        if (!t.primaryKey().isEmpty()) {
            parts.add("CONSTRAINT pk_" + t.name() + " PRIMARY KEY (" + join(t.primaryKey()) + ")");
        }
        return "CREATE TABLE " + t.name() + " (" + join(parts) + ")";
    }

    @Override
    public String renderCreateIndex(TableDef t, IndexDef i) {
        return "CREATE INDEX " + i.name() + " ON " + t.name() + " (" + join(i.columns()) + ")";
    }

    /** 기본키와 컬럼 구성이 같은 인덱스는 만들지 않는다(ORA-01408). H2에서 뺀 보조 인덱스는 Oracle에서는 만든다. */
    @Override
    public boolean wantIndex(TableDef t, IndexDef i) {
        if (i.columns().size() != t.primaryKey().size()) return true;
        for (int n = 0; n < i.columns().size(); n++) {
            if (!i.columns().get(n).equalsIgnoreCase(t.primaryKey().get(n))) return true;
        }
        return false;
    }

    @Override
    public boolean wantColumn(ColumnDef c) {
        return !c.isOracleOmit();
    }

    @Override
    public boolean tableExists(JdbcTemplate jdbc, String table) {
        Integer n = jdbc.queryForObject("SELECT COUNT(*) FROM USER_TABLES WHERE TABLE_NAME = UPPER(?)", Integer.class, table);
        return n != null && n > 0;
    }

    @Override
    public boolean columnExists(JdbcTemplate jdbc, String table, String column) {
        Integer n = jdbc.queryForObject("SELECT COUNT(*) FROM USER_TAB_COLUMNS WHERE TABLE_NAME = UPPER(?) AND COLUMN_NAME = UPPER(?)",
                Integer.class, table, column);
        return n != null && n > 0;
    }

    @Override
    public boolean indexExists(JdbcTemplate jdbc, String index) {
        Integer n = jdbc.queryForObject("SELECT COUNT(*) FROM USER_INDEXES WHERE INDEX_NAME = UPPER(?)", Integer.class, index);
        return n != null && n > 0;
    }

    /** 있는지는 딕셔너리로 확인한다(ORA-00955를 삼키는 방식이 아니다 - 설계서 2.4절). */
    @Override
    public void ensureTable(JdbcTemplate jdbc, TableDef t) {
        if (!tableExists(jdbc, t.name())) {
            jdbc.execute(renderCreateTable(t));
        } else {
            for (ColumnDef c : t.columns()) {
                if (wantColumn(c) && !columnExists(jdbc, t.name(), c.name())) {
                    jdbc.execute("ALTER TABLE " + t.name() + " ADD (" + renderColumn(c) + ")");
                }
            }
        }
        for (IndexDef i : t.indexes()) {
            if (wantIndex(t, i) && !indexExists(jdbc, i.name())) {
                jdbc.execute(renderCreateIndex(t, i));
            }
        }
    }

    @Override
    public List<String> legacyUpgrades(TableDef t) {
        // 신규 스키마뿐이라 보정할 옛 구조가 없다
        return new ArrayList<String>();
    }

    @Override
    public String upsert(TableDef t, List<String> columns) {
        requireKeysIncluded(t, columns);
        List<String> select = new ArrayList<String>();
        List<String> on = new ArrayList<String>();
        List<String> set = new ArrayList<String>();
        List<String> values = new ArrayList<String>();
        for (String c : columns) {
            select.add("? AS " + c);
            values.add("s." + c);
            if (t.isKey(c)) {
                on.add("d." + c + " = s." + c);
            } else {
                // 키 컬럼을 SET에 넣으면 ORA-38104
                set.add("d." + c + " = s." + c);
            }
        }
        StringBuilder sb = new StringBuilder("MERGE INTO ").append(t.name()).append(" d USING (SELECT ")
                .append(join(select)).append(" FROM dual) s ON (");
        for (int i = 0; i < on.size(); i++) {
            if (i > 0) sb.append(" AND ");
            sb.append(on.get(i));
        }
        sb.append(")");
        if (!set.isEmpty()) sb.append(" WHEN MATCHED THEN UPDATE SET ").append(join(set));
        sb.append(" WHEN NOT MATCHED THEN INSERT (").append(join(columns)).append(") VALUES (").append(join(values)).append(")");
        return sb.toString();
    }

    @Override
    public String insertIgnore(TableDef t, List<String> columns) {
        requireKeysOnly(t, columns);
        // 컬럼이 전부 키라 SET 대상이 없어 upsert 문장이 곧 "없을 때만 넣기"다
        return upsert(t, columns);
    }

    @Override
    public String limit(String select, int rows) {
        return select + " FETCH FIRST " + rows + " ROWS ONLY";
    }

    @Override
    public String deleteChunk(String table, String where, int rows) {
        return "DELETE FROM " + table + " WHERE (" + where + ") AND ROWNUM <= " + rows;
    }

    @Override
    public int sqlType(ColumnDef c) {
        switch (c.type()) {
            case VARCHAR:
            case TEXT_LARGE:
                return isClob(c) ? Types.CLOB : Types.VARCHAR;
            case BIGINT:
            case IDENTITY:
            case INTEGER:
            case BOOL01:
                return Types.NUMERIC;
            case DOUBLE:
                return BINARY_DOUBLE;
            default:
                throw new IllegalStateException("타입을 알 수 없습니다: " + c.type());
        }
    }

    @Override
    public boolean isDuplicateKey(Throwable error) {
        if (error instanceof DuplicateKeyException) return true;
        return sqlErrorCodes(error).contains(1);
    }

    @Override
    public boolean isMissingTable(Throwable error) {
        return sqlErrorCodes(error).contains(942);
    }

    @Override
    public boolean isConnectionFailure(Throwable error) {
        int depth = 0;
        for (Throwable t = error; t != null && depth < 20; t = t.getCause(), depth++) {
            if (t instanceof CannotGetJdbcConnectionException || t instanceof DataAccessResourceFailureException) return true;
        }
        for (int code : sqlErrorCodes(error)) {
            // 17002 I/O 오류, 17008 닫힌 접속, 12514 서비스 없음, 12541 리스너 없음, 12170 접속 시간 초과
            if (code == 17002 || code == 17008 || code == 12514 || code == 12541 || code == 12170) return true;
        }
        return false;
    }
}
